#!/usr/bin/env python3
"""Draws the twig pictures of the Foliage mod.

A twig picture is a 16 by 16 block texture with a bare spray of twigs that
grows from the middle of its bottom edge. The mod puts two of them crosswise
into a leaf block wherever the tip of a branch shows: under the small leaf
clumps at the edge of a crown.

There are four sprays, each in three bark colors:

    twigs_brown_0..3   oak, jungle, acacia, mangrove, azalea
    twigs_birch_0..3   birch (the sprays mirrored, so birch and oak differ)
    twigs_dark_0..3    dark oak, spruce, cherry

The sprays were drawn by hand for this mod, as the rows of '#' below. To
change a spray, edit its rows and run, from the project folder:

    python3 tools/make_twigs.py

Needs Python 3 with the Pillow library (pip install pillow). The pictures are
written to src/main/resources/assets/foliage/textures/block/ and are part of
the repository, so nobody has to run this to build the mod.
"""
import os
import random

from PIL import Image

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "main", "resources",
                   "assets", "foliage", "textures", "block")

# Three shades per bark: the usual one, a darker one, a lighter one.
PALETTES = {
    "brown": [(104, 82, 50), (84, 66, 40), (122, 97, 60)],
    "birch": [(110, 88, 84), (88, 68, 68), (132, 108, 102)],
    "dark": [(70, 52, 31), (54, 40, 24), (86, 65, 40)],
}

# The sprays of birch are mirrored left to right.
MIRRORED = {"birch"}

# From this row down a spray is the thick stem and takes the darker shade.
STEM_ROW = 12

