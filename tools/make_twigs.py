def spray(index, palette, mirrored):
    """One twig picture: spray number `index` in the shades of `palette`."""
    rows = SPRAYS[index].strip().split("\n")
    if mirrored:
        rows = [row[::-1] for row in rows]
    # The same shades every time the script runs.
    shades = random.Random(index * 13 + 5)
    picture = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(16):
        for x in range(16):
            if rows[y][x] != "#":
                continue
            shade = palette[1] if y >= STEM_ROW else palette[shades.choice([0, 0, 1, 2])]
            picture.putpixel((x, y), shade + (255,))
    return picture


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, palette in PALETTES.items():
        for index in range(len(SPRAYS)):
            spray(index, palette, name in MIRRORED).save(os.path.join(OUT, f"twigs_{name}_{index}.png"))
    print(f"wrote {len(PALETTES) * len(SPRAYS)} twig pictures to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
